import { expect, test } from "@playwright/test";
import { mkdirSync, writeFileSync } from "node:fs";
import { isolateMotorGeeksApis, sampleCondition } from "./support/motorgeeks-fixtures";

const out = `${process.env.MOTORGEEKS_VISUAL_OUTPUT || "design-references/current/motorgeeks-site-review/after"}/valuation`;
test.describe("MotorGeeks customer valuation and enquiry forms @visual", () => {
  test.skip(!process.env.MOTORGEEKS_VISUAL_URL, "Use the MotorGeeks Playwright config.");
  for (const [width, height] of [[1440, 900], [1280, 800], [768, 1024], [390, 844]]) {
    test(`valuation, errors, photos and completion at ${width}x${height}`, async ({ page }) => {
      mkdirSync(out, { recursive: true });
      const exceptions: string[] = [];
      page.on("pageerror", error => exceptions.push(error.message));
      const api = await isolateMotorGeeksApis(page);
      await page.setViewportSize({ width, height });
      await page.goto(`${process.env.MOTORGEEKS_VISUAL_URL}/valuation`, { waitUntil: "networkidle" });
      const shot = async (name: string) => {
        expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1)).toBe(true);
        await page.evaluate(() => window.scrollTo({ top: 0, behavior: "instant" }));
        await page.screenshot({ path: `${out}/${name}-${width}.png`, fullPage: true });
        const panel = page.locator(".mg-form-panel, .mg-valuation-complete").first();
        await panel.evaluate(element => window.scrollTo({ top: window.scrollY + element.getBoundingClientRect().top - 110, behavior: "instant" }));
        await page.screenshot({ path: `${out}/${name}-${width}-detail.png` });
      };
      await page.getByRole("button", { name: "Next step" }).click();
      await expect(page.locator("main").getByRole("alert")).toContainText("make, model and year");
      await shot("required-details");
      api.lookupFails = true;
      let releaseLookup!: () => void;
      api.lookupWait = new Promise<void>(resolve => { releaseLookup = resolve; });
      await page.getByRole("textbox", { name: "Motorcycle registration", exact: true }).fill("GY26ABC");
      await page.getByRole("button", { name: "Find my bike", exact: true }).click();
      await expect(page.getByRole("button", { name: "Finding your bike…" })).toBeVisible();
      await expect(page.locator(".mg-vrm-row input")).toBeDisabled();
      await shot("lookup-loading");
      releaseLookup();
      await expect(page.locator(".mg-warning-box")).toContainText("You can still continue");
      await page.getByText("Add or correct your bike details", { exact: true }).click();
      await page.getByLabel("Make", { exact: true }).fill("Honda");
      await page.getByLabel("Model", { exact: true }).fill("CB500F");
      await page.getByLabel("Year", { exact: true }).fill("2021");
      await page.getByLabel("Model version (if known)", { exact: true }).fill("Sport");
      await page.getByLabel("Engine size (cc)", { exact: true }).fill("500");
      await page.getByLabel("Fuel type", { exact: true }).fill("Petrol");
      await page.getByLabel("Colour", { exact: true }).fill("Black");
      await page.getByLabel("Mileage (miles)", { exact: true }).fill("12000");
      const owners = page.getByRole("group", { name: "Previous owners (if known)", exact: true });
      const keys = page.getByRole("group", { name: "Number of spare keys", exact: true });
      await expect(owners.getByRole("radio", { checked: true })).toHaveCount(0);
      await expect(keys.getByRole("radio", { checked: true })).toHaveCount(0);
      await owners.getByLabel("2", { exact: true }).check();
      await keys.getByLabel("1", { exact: true }).check();
      await page.getByRole("group", { name: "Is your name on the V5C logbook?", exact: true }).getByLabel("Yes", { exact: true }).check();
      await shot("manual-details");
      await page.getByRole("button", { name: "Next step" }).click();
      await expect(page.getByRole("heading", { level: 1 })).toHaveText("Condition and history");
      await page.getByRole("button", { name: "Back", exact: true }).click();
      await expect(owners.getByLabel("2", { exact: true })).toBeChecked();
      await expect(keys.getByLabel("1", { exact: true })).toBeChecked();
      await page.getByRole("button", { name: "Next step" }).click();
      await page.getByLabel("Overall condition", { exact: true }).selectOption({ label: "Fair - some wear" });
      await page.getByLabel("Service history", { exact: true }).selectOption({ label: "Some service records available" });
      for (const name of ["Does the bike start and can it be ridden?", "Has an insurer ever recorded the bike as a write-off?", "Any mechanical or electrical faults?", "Any scratches, dents, rust or damaged bodywork?"]) await page.getByRole("group", { name, exact: true }).getByLabel("Yes", { exact: true }).check();
      await page.getByRole("group", { name: "Is there any money still owed on finance?", exact: true }).getByLabel("Unsure", { exact: true }).check();
      await page.getByRole("button", { name: "Next step" }).click();
      await expect(page.locator("main").getByRole("alert")).toContainText("write-off category");
      await page.getByLabel("Write-off category", { exact: true }).fill("Not known");
      await page.getByLabel("Tell us about the faults", { exact: true }).fill("Starting problem when cold.");
      await page.getByLabel("Tell us about the damage", { exact: true }).fill("Scratch on left panel.");
      await page.getByLabel("MOT advisories or warnings", { exact: true }).fill("Rear tyre worn.");
      await page.getByLabel("Accessories or changes made to the bike", { exact: true }).fill("Heated grips.");
      await shot("condition-details");
      await page.getByRole("button", { name: "Next step" }).click();
      await expect(page.getByText("0 of 20 photos added.", { exact: false })).toBeVisible();
      await shot("photos-empty");
      await page.locator('input[type="file"]').setInputFiles({ name: "too-large.png", mimeType: "image/png", buffer: Buffer.alloc(4 * 1024 * 1024 + 1) });
      await expect(page.getByText("Please choose one under 4 MB.", { exact: false })).toBeVisible();
      await shot("photo-error");
      await page.locator('input[type="file"]').setInputFiles({ name: "bike.png", mimeType: "image/png", buffer: Buffer.from("iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mP8/x8AAwMCAO+jWZkAAAAASUVORK5CYII=", "base64") });
      await expect(page.getByRole("img", { name: "bike.png", exact: true })).toBeVisible();
      await shot("photo-added");
      await page.getByRole("button", { name: "Remove bike.png", exact: true }).click();
      await expect(page.getByRole("img", { name: "bike.png", exact: true })).toHaveCount(0);
      await page.getByRole("button", { name: "Upload photos later", exact: true }).click();
      await page.getByRole("button", { name: "Next step" }).click();
      await expect(page.getByRole("heading", { level: 1 })).toHaveText("Your contact details");
      await page.getByLabel("First name", { exact: true }).fill("Visual");
      await page.getByLabel("Last name", { exact: true }).fill("Test");
      await page.getByLabel("Email address", { exact: true }).fill("visual@example.test");
      await page.getByLabel("Mobile number", { exact: true }).fill("07123456789");
      await page.getByLabel("Postcode", { exact: true }).fill("SW1A1AA");
      await expect(page.locator(".mg-consent").getByRole("link", { name: "Privacy Policy", exact: true })).toHaveAttribute("href", "/privacy");
      await expect(page.locator(".mg-consent").getByRole("link", { name: "Terms and Conditions", exact: true })).toHaveAttribute("href", "/terms");
      await page.getByRole("button", { name: "Complete my motorcycle profile" }).click();
      await expect(page.locator("main").getByRole("alert")).toContainText("privacy and terms");
      expect(api.submitted).toBeNull();
      await shot("contact-details");
      await page.getByRole("checkbox").check();
      api.submitFails = true;
      await page.getByRole("button", { name: "Complete my motorcycle profile" }).click();
      await expect(page.locator("main").getByRole("alert")).toContainText("Please try again");
      await expect(page.getByLabel("Email address", { exact: true })).toHaveValue("visual@example.test");
      await shot("submit-retry");
      api.submitFails = false;
      await page.getByRole("button", { name: "Complete my motorcycle profile" }).click();
      await expect(page.getByRole("heading", { name: "You're all done!" })).toBeVisible();
      expect(api.submitted?.vehicle).toMatchObject({ derivative: "Sport", engineCapacity: "500" });
      expect(api.submitted?.condition).toMatchObject({ previousOwners: "2", spareKeys: "1", overallCondition: "Average", serviceHistory: "Part history", writtenOff: "yes", writeOffCategory: "Not known", outstandingFinance: "unsure", photosSkipped: true });
      await expect(page.getByText("MG-VISUAL-TEST", { exact: false })).toBeVisible();
      await shot("complete");
      writeFileSync(`${out}/submission-contract-${width}.json`, JSON.stringify(api.submitted, null, 2));
      expect(exceptions).toEqual([]);
    });

    for (const path of ["/contact", "/dealer-access"]) test(`${path} validation, retry and success at ${width}`, async ({ page }) => {
      mkdirSync(out, { recursive: true });
      const errors: string[] = [];
      page.on("pageerror", error => errors.push(error.message));
      const api = await isolateMotorGeeksApis(page);
      await page.setViewportSize({ width, height });
      await page.goto(`${process.env.MOTORGEEKS_VISUAL_URL}${path}`, { waitUntil: "networkidle" });
      if (path === "/dealer-access") await page.getByLabel("Dealership / trading name", { exact: true }).fill("Visual Test Dealership");
      await page.getByLabel("Your name", { exact: true }).fill("Visual Test");
      await page.getByLabel("Email", { exact: true }).fill("visual@example.test");
      await page.getByLabel("Phone number", { exact: true }).fill("07123456789");
      await page.getByLabel("Postcode", { exact: true }).fill("SW1A1AA");
      await page.getByRole("checkbox").check();
      api.contactFails = true;
      await page.locator('button[type="submit"]').click();
      await expect(page.locator("main").getByRole("alert")).toContainText("Please try again");
      await page.screenshot({ path: `${out}/${path.slice(1)}-error-${width}.png`, fullPage: true });
      api.contactFails = false;
      await page.locator('button[type="submit"]').click();
      await expect(page.getByRole("status")).toContainText(path === "/contact" ? "Your message has been sent" : "Application received");
      await page.screenshot({ path: `${out}/${path.slice(1)}-success-${width}.png`, fullPage: true });
      await page.getByRole("button", { name: "Send another message" }).click();
      await expect(page.getByLabel("Your name", { exact: true })).toHaveValue("");
      expect(errors).toEqual([]);
    });
  }

  test("count selections save, restore and support keyboard navigation and older answers", async ({ page }) => {
    const api = await isolateMotorGeeksApis(page, 1, true);
    api.seed.condition_snapshot = { ...sampleCondition, ...{ previousOwners: "8", spareKeys: 2 } };
    await page.goto(`${process.env.MOTORGEEKS_VISUAL_URL}/valuation`, { waitUntil: "networkidle" });
    const owners = page.getByRole("group", { name: "Previous owners (if known)", exact: true });
    const keys = page.getByRole("group", { name: "Number of spare keys", exact: true });
    await expect(owners.getByLabel("8 (saved answer)", { exact: true })).toBeChecked();
    await expect(keys.getByLabel("2", { exact: true })).toBeChecked();
    await expect(owners).toHaveAccessibleDescription("Owners before you. Choose 0 if you bought the bike new.");
    await expect(keys).toHaveAccessibleDescription("Extra keys, not including your main key.");
    await owners.getByLabel("0", { exact: true }).check();
    await keys.getByLabel("0", { exact: true }).check();
    await expect.poll(() => api.saves.at(-1)?.condition).toMatchObject({ previousOwners: "0", spareKeys: "0" });
    await keys.getByLabel("0", { exact: true }).focus();
    await page.keyboard.press("ArrowRight");
    await expect(keys.getByLabel("1", { exact: true })).toBeChecked();
    await expect(owners.getByLabel("0", { exact: true })).toBeChecked();
    await owners.getByLabel("6+", { exact: true }).check();
    await keys.getByLabel("4+", { exact: true }).check();
    await expect.poll(() => api.saves.at(-1)?.condition).toMatchObject({ previousOwners: "6+", spareKeys: "4+" });
    await owners.getByLabel("Not sure", { exact: true }).check();
    await keys.getByLabel("Not sure", { exact: true }).check();
    await expect.poll(() => api.saves.at(-1)?.condition).toMatchObject({ previousOwners: "Not sure", spareKeys: "Not sure" });
    api.seed.condition_snapshot = api.saves.at(-1)!.condition as typeof sampleCondition;
    await page.reload({ waitUntil: "networkidle" });
    await expect(owners.getByLabel("Not sure", { exact: true })).toBeChecked();
    await expect(keys.getByLabel("Not sure", { exact: true })).toBeChecked();
  });
});
